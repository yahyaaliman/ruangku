describe("jadwal sholat", () => {
  it("identik dengan versi Rust", () => {
    for (const [lat, lng, tz, elevation, y, m, d, want] of FIXTURE) {
      const t = compute(y, m, d, { lat, lng, tz, elevation });
      expect([t.imsak, t.subuh, t.terbit, t.dhuha, t.dzuhur, t.ashar, t.maghrib, t.isya]).toEqual(want);
    }
  });
  it("hijriah identik dengan versi Rust", () => {
    for (const [y, m, d, hy, hm, hd] of HFIX) expect(hijri(y, m, d)).toEqual([hy, hm, hd]);
    expect(hijriLabel("2026-10-26")).toBe("14 Jumadil Awal 1448 H");
  });
  it("sepertiga malam dan puasa", () => {
    expect(lastThirdOfNight(18 * 60, 4 * 60 + 30)).toBe(60);
    expect(fastingKinds("2026-10-26")).toEqual(["puasa_senin_kamis", "puasa_ayyamul_bidh"]);
    expect(fastingKinds("2026-10-27")).toEqual(["puasa_ayyamul_bidh"]);
    expect(fastingKinds("2026-10-28")).toEqual([]);
  });
});
